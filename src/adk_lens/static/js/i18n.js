const DICT = { en: EN, fr: FR };
let lang = 'en';

export function initLang() {
  const saved = lsGet('adk-lens.lang');
  const nav = (navigator.language || 'en').toLowerCase();
  lang = saved === 'fr' || saved === 'en' ? saved : nav.startsWith('fr') ? 'fr' : 'en';
  document.documentElement.lang = lang;
  return lang;
}

export function setLang(next) {
  lang = next === 'fr' ? 'fr' : 'en';
  lsSet('adk-lens.lang', lang);
  document.documentElement.lang = lang;
}

export const getLang = () => lang;

export function t(key, vars) {
  let out = DICT[lang][key] ?? EN[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  return out;
}

// Counted phrases: picks `key.zero` (when it exists), `key.one` or `key.other` with the language's own plural rule
// (French counts 0 as singular, English does not).
export function tp(key, n, vars) {
  const count = Number(n) || 0;
  let form = 'other';
  try { form = new Intl.PluralRules(lang).select(count); } catch { form = count === 1 ? 'one' : 'other'; }
  const zero = `${key}.zero`;
  const pick = count === 0 && (DICT[lang][zero] ?? EN[zero]) !== undefined ? zero : `${key}.${form === 'one' ? 'one' : 'other'}`;
  return t(pick, { n: count, ...vars });
}

// Same as t(), but returns DOM nodes with the variables in <b> (safe: text only).
export function tn(key, vars) {
  const tpl = DICT[lang][key] ?? EN[key] ?? key;
  const out = [];
  const re = /\{(\w+)\}/g;
  let last = 0, m;
  while ((m = re.exec(tpl))) {
    if (m.index > last) out.push(document.createTextNode(tpl.slice(last, m.index)));
    const b = document.createElement('b');
    b.textContent = vars && vars[m[1]] !== undefined ? String(vars[m[1]]) : '';
    out.push(b);
    last = m.index + m[0].length;
  }
  if (last < tpl.length) out.push(document.createTextNode(tpl.slice(last)));
  return out;
}
